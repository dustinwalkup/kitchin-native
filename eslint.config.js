const SUPABASE_CLIENT = ['@/lib/supabase', '**/lib/supabase'];

const COLOUR_MESSAGE = 'Use a token from src/ui/theme.ts instead of a colour literal (R16.7).';

module.exports = defineConfig([
  expoConfig,
  // Turns off the stylistic rules that Prettier owns.
  prettierConfig,
  {
    ignores: [
      '.expo/',
      'android/',
      'coverage/',
      'dist/',
      'ios/',
      'web-build/',
      'expo-env.d.ts',
      // Generated by `supabase gen types`; never edited by hand.
      'src/types/database.ts',
    ],
  },
  {
    // Root config files and scripts run in Node, not in the app.
    files: ['*.config.{js,mjs,cjs,ts}', 'scripts/**'],
    languageOptions: { globals: globals.node },
  },
  {
    // Colours come only from theme tokens (R16.7). The theme test compares palette values to SPEC §4.6.
    files: ['src/**/*.{js,jsx,ts,tsx}'],
    ignores: ['src/ui/theme.ts', 'src/ui/theme.test.ts'],
    rules: {
      'no-restricted-syntax': [
        'error',
        { selector: 'Literal[value=/^#[0-9a-f]{3,8}$/i]', message: COLOUR_MESSAGE },
        { selector: 'Literal[value=/^\\s*rgba?\\(/i]', message: COLOUR_MESSAGE },
        { selector: 'TemplateElement[value.raw=/^\\s*rgba?\\(/i]', message: COLOUR_MESSAGE },
      ],
    },
  },
  {
    // Screens and components reach Supabase only through a feature's hooks.ts → api.ts.
    files: ['src/app/**', '**/components/**'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: SUPABASE_CLIENT,
              message:
                "Use the feature's hooks.ts, which calls api.ts, instead of the Supabase client.",
            },
          ],
        },
      ],
    },
  },
  {
    // domain.ts is pure logic (N17).
    files: ['**/domain.ts'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: [
                'react',
                'react/*',
                'react-native',
                'react-native/*',
                '@supabase/*',
                '@tanstack/*',
                ...SUPABASE_CLIENT,
              ],
              message:
                'domain.ts holds pure logic: no React, React Native, Supabase or TanStack imports.',
            },
          ],
        },
      ],
    },
  },
]);
